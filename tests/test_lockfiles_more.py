def test_gemfile_lock_gems_only_without_platform_suffix():
    assert set(lockfiles.gemfile_lock(GEMS)) == {("RubyGems", "ast", "2.4.2"), ("RubyGems", "nokogiri", "1.15.0"),
                                                  ("RubyGems", "parser", "3.3.7.0"), ("RubyGems", "racc", "1.8.1")}
    assert lockfiles.gemfile_lock("") == []


def test_find_picks_up_the_new_names_and_read_reports_broken_files(tmp_path):
    (tmp_path / "web").mkdir()
    (tmp_path / "web" / "pnpm-lock.yaml").write_text(PNPM)
    (tmp_path / "yarn.lock").write_text(CLASSIC)
    (tmp_path / "Gemfile.lock").write_text(GEMS)
    names = sorted(p.name for p in lockfiles.find(str(tmp_path)))
    assert names == ["Gemfile.lock", "pnpm-lock.yaml", "yarn.lock"]
    pkgs, err = lockfiles.read(tmp_path / "Gemfile.lock")
    assert err is None and len(pkgs) == 4


def test_licence_lookup_url_for_each_ecosystem():
    from judged import deps
    seen = []
    get = lambda url: seen.append(url) or {"licenses": ["MIT"]}
    assert deps.licence_of(("Maven", "org.apache.commons:commons-lang3", "3.12.0"), get) == "MIT"
    deps.licence_of(("RubyGems", "rake", "13.0.6"), get)
    deps.licence_of(("npm", "@babel/core", "7.0.0"), get)
    assert seen[0].endswith("/systems/maven/packages/org.apache.commons%3Acommons-lang3/versions/3.12.0")
    assert "/systems/rubygems/packages/rake/" in seen[1] and "/packages/%40babel%2Fcore/" in seen[2]
    assert deps.licence_of(("Hex", "a", "1"), get) is None and len(seen) == 3        # no source covers it: no request, no guess
