def test_pnpm_registry_packages_only_and_entries_do_not_leak_into_each_other():
    got = set(lockfiles.pnpm_lock(PNPM))
    assert got == {("npm", "@a2a-js/sdk", "0.3.13"), ("npm", "@humanwhocodes/retry", "0.4.3"), ("npm", "react-grid-layout", "1.5.3")}
    # retry sits right before a tarball entry and must not be dropped with it; "repo:" inside a deprecated text is not a git source


def test_pnpm_old_formats_and_empty():
    assert lockfiles.pnpm_lock("") == [] and lockfiles.pnpm_lock("lockfileVersion: 5.4\n") == []
    v6 = "lockfileVersion: '6.0'\n\npackages:\n\n  /@babel/core@7.20.0:\n    resolution: {integrity: x}\n\n  /lodash@4.17.21:\n    resolution: {integrity: y}\n"
    assert set(lockfiles.pnpm_lock(v6)) == {("npm", "@babel/core", "7.20.0"), ("npm", "lodash", "4.17.21")}
    v5 = "lockfileVersion: 5.4\n\npackages:\n\n  /lodash/4.17.21:\n    resolution: {integrity: y}\n"
    assert lockfiles.pnpm_lock(v5) == [("npm", "lodash", "4.17.21")]


